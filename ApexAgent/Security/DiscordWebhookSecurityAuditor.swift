import Foundation
import CryptoKit

// MARK: - Discord Webhook & Gateway Security Auditor (Batch 71)

/// Configuration policy for Discord webhook security auditing.
public struct DiscordSecurityConfig: Sendable, Codable, Equatable {
    /// Maximum allowed age in seconds for inbound requests to prevent replay attacks.
    public var maxReplayToleranceSeconds: TimeInterval
    /// Maximum character length for outbound webhook message content (Discord limit is 2000).
    public var maxContentLength: Int
    /// Strip or neutralize `@everyone` and `@here` mentions.
    public var neutralizeMassMentions: Bool
    /// Strip role mentions `<@&role_id>`.
    public var stripRoleMentions: Bool
    /// Hex-encoded Ed25519 public key for signature validation.
    public var ed25519PublicKeyHex: String?
    /// Shared HMAC secret key for alternative tokenized verification.
    public var sharedSecret: String?

    public init(
        maxReplayToleranceSeconds: TimeInterval = 300.0,
        maxContentLength: Int = 2000,
        neutralizeMassMentions: Bool = true,
        stripRoleMentions: Bool = true,
        ed25519PublicKeyHex: String? = nil,
        sharedSecret: String? = nil
    ) {
        self.maxReplayToleranceSeconds = maxReplayToleranceSeconds
        self.maxContentLength = maxContentLength
        self.neutralizeMassMentions = neutralizeMassMentions
        self.stripRoleMentions = stripRoleMentions
        self.ed25519PublicKeyHex = ed25519PublicKeyHex
        self.sharedSecret = sharedSecret
    }
}

/// Inbound webhook request container for security auditing.
public struct DiscordInboundWebhookRequest: Sendable {
    public let timestampHeader: String?
    public let signatureHeader: String?
    public let rawBody: Data
    public let headers: [String: String]

    public init(
        timestampHeader: String?,
        signatureHeader: String?,
        rawBody: Data,
        headers: [String: String] = [:]
    ) {
        self.timestampHeader = timestampHeader
        self.signatureHeader = signatureHeader
        self.rawBody = rawBody
        self.headers = headers
    }
}

/// Severity of a Discord security violation.
public enum DiscordSecurityViolationSeverity: String, Sendable, Codable, Equatable {
    case high
    case medium
    case low
}

/// Detailed violation record from Discord webhook auditing.
public struct DiscordSecurityViolation: Sendable, Codable, Equatable {
    public let code: String
    public let message: String
    public let severity: DiscordSecurityViolationSeverity

    public init(code: String, message: String, severity: DiscordSecurityViolationSeverity) {
        self.code = code
        self.message = message
        self.severity = severity
    }
}

/// Audit report generated by DiscordWebhookSecurityAuditor.
public struct DiscordWebhookAuditReport: Sendable, Codable, Equatable {
    public let passed: Bool
    public let score: Double
    public let evaluatedChecksCount: Int
    public let violations: [DiscordSecurityViolation]
    public let signatureValid: Bool
    public let replaySafe: Bool
    public let payloadValid: Bool

    public init(
        passed: Bool,
        score: Double,
        evaluatedChecksCount: Int,
        violations: [DiscordSecurityViolation],
        signatureValid: Bool,
        replaySafe: Bool,
        payloadValid: Bool
    ) {
        self.passed = passed
        self.score = score
        self.evaluatedChecksCount = evaluatedChecksCount
        self.violations = violations
        self.signatureValid = signatureValid
        self.replaySafe = replaySafe
        self.payloadValid = payloadValid
    }
}

/// Result of outbound message content sanitization.
public struct DiscordOutboundPayloadSanitizationResult: Sendable, Equatable {
    public let originalContent: String
    public let sanitizedContent: String
    public let wasTruncated: Bool
    public let neutralizedMentionsCount: Int
    public let isAcceptable: Bool
}

/// Rate-limit telemetry parsed from Discord response headers.
public struct DiscordRateLimitStatus: Sendable, Equatable {
    public let limit: Int?
    public let remaining: Int?
    public let resetEpoch: TimeInterval?
    public let resetAfterSeconds: TimeInterval?
    public let retryAfterSeconds: TimeInterval?
    public let isThrottled: Bool
    public let recommendedWaitSeconds: TimeInterval
}

/// Security auditor for inbound and outbound Discord interactions.
public enum DiscordWebhookSecurityAuditor {

    // MARK: - Inbound Request Verification

    /// Audits an inbound Discord webhook request for Ed25519/HMAC signature integrity, timestamp replay, and payload sanity.
    public static func auditInboundRequest(
        _ request: DiscordInboundWebhookRequest,
        config: DiscordSecurityConfig,
        now: Date = Date()
    ) -> DiscordWebhookAuditReport {
        var violations: [DiscordSecurityViolation] = []
        var signatureValid = false
        var replaySafe = false
        var payloadValid = true

        // 1. Timestamp Replay Verification
        if let timestampStr = request.timestampHeader, let timestampSec = Double(timestampStr) {
            let requestDate = Date(timeIntervalSince1970: timestampSec)
            let age = abs(now.timeIntervalSince(requestDate))
            if age > config.maxReplayToleranceSeconds {
                violations.append(DiscordSecurityViolation(
                    code: "REPLAY_TOLERANCE_EXCEEDED",
                    message: "Timestamp age of \(String(format: "%.1f", age))s exceeds max tolerance of \(config.maxReplayToleranceSeconds)s.",
                    severity: .high
                ))
            } else {
                replaySafe = true
            }
        } else {
            violations.append(DiscordSecurityViolation(
                code: "MISSING_TIMESTAMP_HEADER",
                message: "Missing or malformed X-Signature-Timestamp header.",
                severity: .high
            ))
        }

        // 2. Cryptographic Signature Verification
        if let signatureHex = request.signatureHeader, !signatureHex.isEmpty {
            if let pubKeyHex = config.ed25519PublicKeyHex, !pubKeyHex.isEmpty {
                let timestampData = (request.timestampHeader ?? "").data(using: .utf8) ?? Data()
                var signedPayload = timestampData
                signedPayload.append(request.rawBody)

                signatureValid = verifyEd25519Signature(
                    signatureHex: signatureHex,
                    data: signedPayload,
                    publicKeyHex: pubKeyHex
                )
                if !signatureValid {
                    violations.append(DiscordSecurityViolation(
                        code: "INVALID_ED25519_SIGNATURE",
                        message: "Ed25519 cryptographic signature failed verification.",
                        severity: .high
                    ))
                }
            } else if let secret = config.sharedSecret, !secret.isEmpty {
                signatureValid = verifyHMACSignature(
                    signatureHex: signatureHex,
                    data: request.rawBody,
                    secret: secret
                )
                if !signatureValid {
                    violations.append(DiscordSecurityViolation(
                        code: "INVALID_HMAC_SIGNATURE",
                        message: "HMAC-SHA256 signature mismatch.",
                        severity: .high
                    ))
                }
            } else {
                violations.append(DiscordSecurityViolation(
                    code: "NO_VERIFICATION_KEY_CONFIGURED",
                    message: "Neither Ed25519 public key nor HMAC secret is configured.",
                    severity: .high
                ))
            }
        } else {
            violations.append(DiscordSecurityViolation(
                code: "MISSING_SIGNATURE_HEADER",
                message: "Missing or empty X-Signature-Ed25519 header.",
                severity: .high
            ))
        }

        // 3. Payload sanity
        if request.rawBody.isEmpty {
            payloadValid = false
            violations.append(DiscordSecurityViolation(
                code: "EMPTY_REQUEST_BODY",
                message: "Inbound webhook body is completely empty.",
                severity: .medium
            ))
        }

        let evaluatedChecks = 3
        let passed = violations.isEmpty
        let score = passed ? 100.0 : max(0.0, 100.0 - Double(violations.count) * 33.3)

        return DiscordWebhookAuditReport(
            passed: passed,
            score: score,
            evaluatedChecksCount: evaluatedChecks,
            violations: violations,
            signatureValid: signatureValid,
            replaySafe: replaySafe,
            payloadValid: payloadValid
        )
    }

    // MARK: - Outbound Payload Sanitization

    /// Sanitizes outbound message content to prevent mass pings, role pings, and length violations.
    public static func sanitizeOutboundPayload(
        content: String,
        config: DiscordSecurityConfig = DiscordSecurityConfig()
    ) -> DiscordOutboundPayloadSanitizationResult {
        var sanitized = content
        var neutralizedCount = 0

        if config.neutralizeMassMentions {
            let patterns = ["@everyone", "@here"]
            for pattern in patterns {
                let count = sanitized.components(separatedBy: pattern).count - 1
                if count > 0 {
                    neutralizedCount += count
                    // Insert a zero-width space after the '@' to defang the ping
                    sanitized = sanitized.replacingOccurrences(of: pattern, with: "@\u{200B}" + pattern.dropFirst())
                }
            }
        }

        if config.stripRoleMentions {
            // Match <@&1234567890>
            let regex = try? NSRegularExpression(pattern: "<@&(\\d+)>", options: [])
            if let regex {
                let range = NSRange(sanitized.startIndex..<sanitized.endIndex, in: sanitized)
                let matches = regex.matches(in: sanitized, options: [], range: range)
                neutralizedCount += matches.count
                sanitized = regex.stringByReplacingMatches(in: sanitized, options: [], range: range, withTemplate: "[role-mention-redacted]")
            }
        }

        let wasTruncated: Bool
        if sanitized.count > config.maxContentLength {
            sanitized = String(sanitized.prefix(config.maxContentLength))
            wasTruncated = true
        } else {
            wasTruncated = false
        }

        let acceptable = !sanitized.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty

        return DiscordOutboundPayloadSanitizationResult(
            originalContent: content,
            sanitizedContent: sanitized,
            wasTruncated: wasTruncated,
            neutralizedMentionsCount: neutralizedCount,
            isAcceptable: acceptable
        )
    }

    // MARK: - Rate Limit Header Parsing

    /// Parses Discord standard rate limit headers to determine backoff and throttling state.
    public static func evaluateRateLimits(
        headers: [String: String],
        now: Date = Date()
    ) -> DiscordRateLimitStatus {
        let normalized = Dictionary(uniqueKeysWithValues: headers.map { ($0.key.lowercased(), $0.value) })

        let limit = normalized["x-ratelimit-limit"].flatMap(Int.init)
        let remaining = normalized["x-ratelimit-remaining"].flatMap(Int.init)
        let resetEpoch = normalized["x-ratelimit-reset"].flatMap(Double.init)
        let resetAfter = normalized["x-ratelimit-reset-after"].flatMap(Double.init)
        let retryAfter = normalized["retry-after"].flatMap(Double.init)

        var isThrottled = false
        var waitSeconds: TimeInterval = 0.0

        if let retry = retryAfter, retry > 0 {
            isThrottled = true
            waitSeconds = retry
        } else if let rem = remaining, rem == 0 {
            isThrottled = true
            if let after = resetAfter, after > 0 {
                waitSeconds = after
            } else if let epoch = resetEpoch {
                waitSeconds = max(0.0, epoch - now.timeIntervalSince1970)
            }
        }

        return DiscordRateLimitStatus(
            limit: limit,
            remaining: remaining,
            resetEpoch: resetEpoch,
            resetAfterSeconds: resetAfter,
            retryAfterSeconds: retryAfter,
            isThrottled: isThrottled,
            recommendedWaitSeconds: waitSeconds
        )
    }

    // MARK: - Cryptographic Helpers

    /// Verifies an Ed25519 signature given hex-encoded signature and public key.
    public static func verifyEd25519Signature(
        signatureHex: String,
        data: Data,
        publicKeyHex: String
    ) -> Bool {
        guard let signatureData = Data(hexString: signatureHex),
              let publicKeyData = Data(hexString: publicKeyHex) else {
            return false
        }
        guard signatureData.count == 64, publicKeyData.count == 32 else {
            return false
        }

        guard let publicKey = try? Curve25519.Signing.PublicKey(rawRepresentation: publicKeyData) else {
            return false
        }

        return publicKey.isValidSignature(signatureData, for: data)
    }

    /// Verifies an HMAC-SHA256 signature given hex-encoded signature and secret.
    public static func verifyHMACSignature(
        signatureHex: String,
        data: Data,
        secret: String
    ) -> Bool {
        guard let signatureData = Data(hexString: signatureHex) else {
            return false
        }
        let key = SymmetricKey(data: secret.data(using: .utf8) ?? Data())
        let computed = HMAC<SHA256>.authenticationCode(for: data, using: key)
        return Data(computed) == signatureData
    }
}

// MARK: - Hex Parsing Helper

private extension Data {
    init?(hexString: String) {
        let cleaned = hexString.trimmingCharacters(in: .whitespacesAndNewlines)
        guard cleaned.count % 2 == 0 else { return nil }

        var data = Data(capacity: cleaned.count / 2)
        var index = cleaned.startIndex
        while index < cleaned.endIndex {
            let nextIndex = cleaned.index(index, offsetBy: 2)
            let byteString = cleaned[index..<nextIndex]
            guard let byte = UInt8(byteString, radix: 16) else { return nil }
            data.append(byte)
            index = nextIndex
        }
        self = data
    }
}
